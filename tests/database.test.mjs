test('an admin cannot verify their own work, and a reviewer must retain their role at decision time', async () => {
  await as(admin)
  const id = randomUUID()
  await scalar("select file_issue($1,'QA retest','Recheck login','high',$2,$3,'me','{}')", [workspace,admin,id])
  const act = (action, request = null) => scalar("select transition_issue($1,$2,'Independent retest','{}',$3)", [id,action,request])
  const requestId = () => scalar('select verification_request_id from issues where id=$1', [id])
  await act('start')
  await scalar("select add_evidence($1,'note','Login retest log')", [id])
  await act('request')
  const first = await requestId()
  await assert.rejects(act('approve',first), /independent reviewer/)
  assert.equal(await scalar('select count(*)::int from resolution_verifications where issue_id=$1',[id]), 0)
  await as(verifier)
  assert.equal(await requestId(), first)
  await as(admin)
  await scalar("select set_member_role($1,$2,'member')", [workspace,verifier])
  await as(verifier)
  await assert.rejects(act('approve',first), /Role cannot perform/)
  await as(admin)
  await scalar("select set_member_role($1,$2,'verifier')", [workspace,verifier])
  await as(verifier)
  await act('reject',first)
  await as(admin)
  await act('request')
  const second = await requestId()
  await as(verifier)
  await assert.rejects(act('approve',first), /request changed/)
  await act('approve',second)
  assert.equal(await scalar('select count(distinct request_id)::int from resolution_verifications where issue_id=$1',[id]),2)
})
